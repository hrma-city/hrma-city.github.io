  /* 一日流水线：按表 M 时间轴固定顺序 */
  var PIPELINE = ["s11", "s12", "s06", "s02", "s04", "s10", "s14"];

  /* ---------------- 引擎 ---------------- */
  function newState() {
    return { rev: 60, guest: 60, owner: 60, team: 60 };
  }

  function apply(st, fx) {
    GAUGES.forEach(function (g) {
      if (typeof fx[g.k] === "number") {
        st[g.k] = Math.max(0, Math.min(100, st[g.k] + fx[g.k]));
      }
    });
    return st;
  }

  /* Reigns 式：任一仪表触底或爆表就结束 */
  function over(st) {
    for (var i = 0; i < GAUGES.length; i++) {
      var g = GAUGES[i], v = st[g.k];
      if (v <= 0)  return { done: true, g: g, why: "bottom" };
      if (v >= 100) return { done: true, g: g, why: "top" };
    }
    return { done: false };
  }

  function byId(id) {
    for (var i = 0; i < SCENARIOS.length; i++) if (SCENARIOS[i].id === id) return SCENARIOS[i];
    return null;
  }

  /* 洗牌（值班叙事用） */
  function shuffled(arr) {
    var a = arr.slice();
    for (var i = a.length - 1; i > 0; i--) {
      var j = Math.floor(Math.random() * (i + 1));
      var t = a[i]; a[i] = a[j]; a[j] = t;
    }
    return a;
  }

  w.RMSIM = {
    GAUGES: GAUGES,
    SCENARIOS: SCENARIOS,
    PIPELINE: PIPELINE,
    newState: newState,
    apply: apply,
    over: over,
    byId: byId,
    shuffled: shuffled
  };
