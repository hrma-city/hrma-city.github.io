def codex_tbl(d, key, highlight=None, notes="", **kw):
    """渲染一张《法典》判定表页（阈值来自 T，禁止在调用处改写）。"""
    t = dict(T[key])
    ratios = t.pop("ratios", None)
    note = t.pop("note", None)
    t.update(kw)
    return d.table(col_ratios=ratios, note=note, highlight=highlight,
                   notes=notes, **t)


def data_tbl(d, spec, title, subtitle=None, note=None, highlight=None,
             notes="", eyebrow=None, **kw):
    """渲染一张普通数据表页（云璟基线 / 客源 / 渠道 / 竞对等）。"""
    return d.table(badge=None, title=title, headers=spec["headers"],
                   rows=spec["rows"], col_ratios=spec.get("ratios"),
                   subtitle=subtitle, note=note, highlight=highlight,
                   notes=notes, **kw)
